  function keepDialogFromTakingPointerFocus(event: PointerEvent) {
    if (event.button !== 0 || !(event.target instanceof Element)) return
    const interactive = event.target.closest('button, a, input, textarea, select, [role="button"], [role="tab"], [role="option"], [contenteditable="true"]')
    if (!interactive) event.preventDefault()
  }

  function focusSettingsRegion(region: 'navigation' | 'content') {
    stopObservingSelectLifecycle()
    settingsContentMode = 'browse'
    settingsRegion = region
    const target = region === 'navigation' ? navigationRegionEl : contentRegionEl
    target?.focus({ preventScroll: true })
    if (region === 'content') scheduleSettingsControlSelection()
  }

  function isAvailableSettingsControl(control: HTMLElement): boolean {
    return !control.hidden
      && !control.matches(':disabled')
      && control.getAttribute('aria-disabled') !== 'true'
      && control.getAttribute('aria-hidden') !== 'true'
      && !control.closest('[hidden], [aria-hidden="true"]')
  }

  function getSettingsControls(): HTMLElement[] {
    if (!contentPanelEl) return []
    const controls = Array.from(contentPanelEl.querySelectorAll<HTMLElement>(SETTINGS_CONTROL_SELECTOR))
      .filter(isAvailableSettingsControl)
    const orderGroups = new Map<HTMLElement, Array<{ control: HTMLElement; index: number; order: number }>>()
    controls.forEach((control, index) => {
      const group = control.closest<HTMLElement>('[data-settings-keyboard-order-group]')
      const order = Number(control.dataset.settingsKeyboardOrder)
      if (!group || !Number.isFinite(order)) return
      const entries = orderGroups.get(group) ?? []
      entries.push({ control, index, order })
      orderGroups.set(group, entries)
    })

    for (const entries of orderGroups.values()) {
      const slots = entries.map(({ index }) => index).sort((left, right) => left - right)
      const ordered = [...entries].sort((left, right) => left.order - right.order)
      slots.forEach((slot, index) => { controls[slot] = ordered[index].control })
    }
    return controls
  }

  function getSettingsFooterActions(): HTMLElement[] {
    if (!contentFooterEl) return []
    return Array.from(contentFooterEl.querySelectorAll<HTMLElement>(
      '[data-settings-footer-action]:not(:disabled):not([aria-disabled="true"])',
    )).filter(isAvailableSettingsControl)
  }

  function getSettingsContentItems(): SettingsContentItem[] {
    const controls = getSettingsControls().map((element): SettingsContentItem => ({ kind: 'control', element }))
    const footerActions = getSettingsFooterActions()
      .map((element): SettingsContentItem => ({ kind: 'footer', element }))
    return [...controls, ...footerActions]
  }

  function getSettingsHorizontalGroupControls(
    group: HTMLElement,
    includeUnavailable = false,
  ): HTMLElement[] {
    const controls = Array.from(group.querySelectorAll<HTMLElement>(
      '[data-settings-horizontal-action]',
